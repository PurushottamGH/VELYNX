def write_protocol(root: Path, protocol: Mapping[str, object]) -> str:
    """Write canonical JSON plus its sidecar hash and return the hash."""
    path = root / PROTOCOL_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = dict(protocol)
    digest = protocol_hash(payload)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (root / PROTOCOL_HASH_PATH).write_text(digest + "\n", encoding="utf-8")
    return digest


def load_and_verify_protocol(root: Path) -> Dict[str, object]:
    path = root / PROTOCOL_PATH
    hash_path = root / PROTOCOL_HASH_PATH
    if not path.exists() or not hash_path.exists():
        raise ProtocolRefusal("canonical protocol or protocol hash sidecar is missing")
    protocol = json.loads(path.read_text(encoding="utf-8"))
    expected = hash_path.read_text(encoding="utf-8").strip()
    verify_protocol_digest(protocol, expected)
    if protocol.get("HEAD") != git_head(root):
        raise ProtocolRefusal("protocol HEAD drifted")
    current_protected = protected_surface_manifest(root)
    recorded_protected = protocol.get("protected_surface", {})
    verify_protected_surface(root, str(recorded_protected.get("aggregate_sha256")))
    if store_content_hash(root) != protocol.get("store_content_hash"):
        raise ProtocolRefusal("canonical Store content hash drifted")
    current_implementation = implementation_hashes(root)
    if current_implementation != protocol.get("implementation_hashes"):
        raise ProtocolRefusal("canonical implementation hash drifted")
    verify_master_seed_set(protocol)
    return protocol


def require_decisive_allowed(protocol: Mapping[str, object], root: Path | None = None) -> None:
    """Gate decisive execution on a closed SESOI *and* honest provenance.

    Both gates always run.  ``root`` only selects *which* tree the source state
    is re-derived from, defaulting to the repository this module lives in; it is
    never a way to skip the check, because a recorded ``source_state`` describes
    when the protocol was written, not when the experiment is about to run.

    Passing ``root=None`` used to skip provenance entirely, which was survivable
    only while SESOI was OPEN and refused first.  Now that SESOI is CLOSED that
    path would authorise a decisive run against unverified source, so it does not
    exist any more.
    """
    sesoi = protocol.get("SESOI", {})
    if sesoi.get("status") != "CLOSED" or sesoi.get("value") is None:
        raise ProtocolRefusal("decisive execution is prohibited while SESOI is OPEN")
    verify_source_state(REPO_ROOT if root is None else root)


