class ProtocolRefusal(RuntimeError):
    """Raised when protocol-critical identity or launch conditions drift."""


def canonical_json(value: object) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def protocol_hash(protocol: Mapping[str, object]) -> str:
    """Hash the canonical protocol without a self-referential hash field."""
    payload = dict(protocol)
    payload.pop("protocol_sha256", None)
    return hashlib.sha256(canonical_json(payload).encode("utf-8")).hexdigest()


def verify_protocol_digest(protocol: Mapping[str, object], expected: str) -> None:
    """Refuse a protocol payload whose canonical digest changed."""
    actual = protocol_hash(protocol)
    if actual != expected:
        raise ProtocolRefusal(f"protocol SHA256 mismatch: expected {expected}, got {actual}")


def protected_surface_manifest(root: Path) -> Dict[str, object]:
    """Hash the certification-defined protected surface, including generated bytecode."""
    files: set[Path] = set()
    for directory in _PROTECTED_DIRS:
        base = root / directory
        if base.exists():
            files.update(path for path in base.rglob("*") if path.is_file())
    for filename in _PROTECTED_FILES:
        path = root / filename
        if path.is_file():
            files.add(path)
    outputs = root / "outputs"
    if outputs.exists():
        files.update(path for path in outputs.glob("P1_V2*") if path.is_file())
        files.update(path for path in outputs.glob("stage3*") if path.is_file())
    entries = [
        {
            "path": path.relative_to(root).as_posix(),
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        }
        for path in sorted(files, key=lambda item: item.relative_to(root).as_posix())
    ]
    return {
        "count": len(entries),
        "entries": entries,
        "aggregate_sha256": hashlib.sha256(canonical_json(entries).encode("utf-8")).hexdigest(),
    }


def store_content_hash(root: Path) -> str:
    """Read the canonical Store hash without mutating the Store."""
    from ros.store import Store

    return Store.load(root / "science/SKB_RECORDS_v1.0.yaml").content_hash()


def verify_protected_surface(root: Path, expected_aggregate: str) -> None:
    """Refuse any protected-surface mutation."""
    actual = str(protected_surface_manifest(root)["aggregate_sha256"])
    if actual != expected_aggregate:
        raise ProtocolRefusal(
            f"protected surface hash mismatch: expected {expected_aggregate}, got {actual}"
        )


def verify_master_seed_set(protocol: Mapping[str, object], expected: Sequence[int] = MASTER_SEEDS) -> None:
    """Refuse a seed-set change even when a caller recomputes a new digest."""
    actual = tuple(int(seed) for seed in protocol.get("master_seeds", ()))
    expected_tuple = tuple(int(seed) for seed in expected)
    if actual != expected_tuple:
        raise ProtocolRefusal(f"master seed set drifted: expected {expected_tuple}, got {actual}")


def implementation_hashes(root: Path) -> Dict[str, str]:
    return {
        path: hashlib.sha256((root / path).read_bytes()).hexdigest()
        for path in IMPLEMENTATION_FILES
        if (root / path).is_file()
    }


def git_head(root: Path) -> str:
    return subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=root, text=True
    ).strip()


def _head_blobs(root: Path, paths: Sequence[str]) -> Dict[str, str]:
    """Blob hash of each path as it exists in the HEAD *tree*, if at all."""
    if not paths:
        return {}
    raw = subprocess.check_output(
        ["git", "ls-tree", "-r", "-z", "HEAD", "--", *paths], cwd=root, text=True
    )
    blobs: Dict[str, str] = {}
    for record in raw.split("\0"):
        if not record:
            continue
        meta, _, path = record.partition("\t")
        parts = meta.split()
        if len(parts) >= 3 and parts[1] == "blob":
            blobs[path] = parts[2]
    return blobs


def _worktree_blobs(root: Path, paths: Sequence[str]) -> Dict[str, str]:
    """Blob hash of the bytes actually on disk, with gitattributes filters applied."""
    if not paths:
        return {}
    raw = subprocess.check_output(
        ["git", "hash-object", "--", *paths], cwd=root, text=True
    )
    return dict(zip(paths, raw.split()))


def source_state(root: Path) -> Dict[str, object]:
    """Identify the *actual* source state that produced this implementation.

    Recording ``HEAD`` alone is not provenance: a file can be untracked at
    HEAD, or tracked and locally modified, and the protocol would still claim
    the commit.  This records, per implementation file, the blob git would
    resolve at HEAD against the blob of the bytes on disk, so a reader can tell
    exactly which of the two the experiment ran.

    ``clean`` is true only when every implementation file is tracked at HEAD
    *and* byte-identical to it.  While it is false the recorded HEAD does not
    describe the code, and :func:`require_decisive_allowed` refuses.
    """
    present = [path for path in IMPLEMENTATION_FILES if (root / path).is_file()]
    head = _head_blobs(root, present)
    work = _worktree_blobs(root, present)
    files = {}
    for path in IMPLEMENTATION_FILES:
        if path not in present:
            files[path] = {"status": "missing", "head_blob": head.get(path), "worktree_blob": None}
            continue
        head_blob, work_blob = head.get(path), work.get(path)
        if head_blob is None:
            status = "untracked_at_head"
        elif head_blob != work_blob:
            status = "modified"
        else:
            status = "clean"
        files[path] = {"status": status, "head_blob": head_blob, "worktree_blob": work_blob}
    dirty = sorted(p for p, row in files.items() if row["status"] != "clean")
    return {
        "head": git_head(root),
        "head_describes_implementation": not dirty,
        "clean": not dirty,
        "divergent_files": dirty,
        "files": files,
    }


def verify_source_state(root: Path) -> None:
    """Refuse when the recorded commit does not describe the code on disk."""
    state = source_state(root)
    if not state["clean"]:
        raise ProtocolRefusal(
            "source state does not match HEAD; the following implementation files are "
            f"untracked or modified: {state['divergent_files']!r}"
        )


